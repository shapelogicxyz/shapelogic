#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Fails when a tracked file has a name of BurrTools' "bt" kinds that the
# rename to sl / SHAPELOGIC_ took out (docs/CLEANUP-BT-NAMES.md): BT_ and
# BTE_ macros, the bt:: namespace, the btcore / btengine / bt_tests
# targets, BT_ environment variables, window.bt and btApp, the bt:
# channels, the bt-app scheme, _bt_ exports, bt- temp folders. Agents copy
# names from old code and docs, so without this check they come back.
# Run by `just check` (and alone: `just check-names`). Exit 0 when no such
# name is left; else each one, as path:line: name, and exit 1.
#
# What the check does not look at: the dated records and the finished
# plans (they say what was true then), recorded data and generated files,
# binary files and this script. What it allows: the names below that
# stay, each where it may be. Needs git with PCRE (git grep -P).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# The old kinds. A bare `bt` or `BT` is a whole word; the CSS class `bt`,
# the plan's file name and a `bt:` channel come first, so they match with
# what is beside them.
w='A-Za-z0-9_'
kinds=(
  "\\.bt(?=[ {\\[]|:has)"                     # the CSS class: .cfm .bt, .bt:has(
  'class="bt"'                                # the same in HTML
  'CLEANUP-BT-NAMES'                          # the rename's plan, by its file name
  "(?<![$w])bt:[a-z][a-z-]*"                  # an IPC channel bt:call
  "(?<![$w])bt(?![$w])"                       # bt, bt::, bt-app, bt/, window.bt
  "(?<![A-Za-z0-9])_*bt_[$w]*"                # bt_tests, _bt_start, bt_test_
  "(?<![$w])[Bb]t[A-Z][$w]*"                  # btApp, BtBridge, btJson
  "[$w]*BTE?_[$w]*"                           # BT_ASSERT, BTE_TRY, __BT_VERSION__, -DBT_WERROR
  "(?<![$w])BT[A-Z0-9]{2,}(?![$w])"           # BTSOLVE2 and the other signatures
  "(?<![$w])(?:lib)?bt(?:core|engine|classic|solve)[$w]*"   # btcore, libbtcore
  "(?<![$w])BT(?![$w])"                       # BT
)
pattern=$(IFS='|'; echo "${kinds[*]}")

# Paths never looked at: dated records, finished plans, recorded data and
# generated files (git pathspecs).
skip=(
  ':!docs/decisions/'            # dated records
  ':!docs/handoff/'              # dated records
  ':!RELEASE_NOTES.md'           # a dated record
  ':!release/'                   # release notes and files
  ':!docs/PLAN.md'               # finished plans: dated records
  ':!docs/DEFERRED-PLAN.md'
  ':!docs/FRONTEND-PLAN.md'
  ':!docs/SLIDE-TWO-ENDS-PLAN.md'
  ':!docs/V2-IDEAS-PLAN.md'
  ':!docs/CLEANUP-BT-NAMES.md'   # the rename's plan names the old names
  ':!docs/mockup/'               # the mockup, read-only
  ':!tests/data/'                # fixtures and recordings
  ':!tests/regression/baseline/' # recorded answers
  ':!*.xmpuzzle'                 # puzzle files
  ':!site/public/demo/'          # generated by just site-demo
  ':!web/src/engine/api.generated.ts'   # generated by just app-gen
  ':!web/fake-engine/recordings/'       # recorded sessions
  ':!*package-lock.json'         # npm's lock files (hashes)
  ':!AUTHORS'                    # credits
  ':!COPYING'                    # the license
  ':!tests/check-names.sh'       # this script
)

# Names that stay: a path (a glob; * matches /) and the name as the kinds
# above match it, leading underscores dropped. Names the kinds do not match
# need no line: the original's BT2 solver (BT2, bt2, pausedBt2),
# burrtoolsclassic, BURRTOOLS_*, btn, btoa, subtree.
allow=(
  # on-disk signatures: users' saved files carry them
  '*  BTSOLVE2'      # the .slsolve paused solve, the original's format
  '*  BTZ1'          # packed sections, the original's format
  '*  BTPANEX3'      # a Panex search's saved folder, from before milliseconds
  '*  BTPANEX4'      # and now
  '*  BTSLKEY2'      # a slide search's key set file, v1.9 and earlier
  '*  BTSLKEY3'      # and now
  '*  BTSLSV01'      # a slide search's state.bin, one end and both
  '*  BTSLSV02'
  # signatures the readers must refuse
  'tests/unit/*  BTSOLVE1'
  'tests/unit/*  BTSLKEY4'
  # a solver name files and the command line accept
  '*  btclassic'
  # the original's own names, where the code or a doc cites them
  '*  BT_ROT_DEBUG'
  '*  BT_ROT_DUMP'
  '*  bt_message'
  '*  bt_assert'
  # the rename's plan: docs/CLEANUP-BT-NAMES.md
  '*  CLEANUP-BT-NAMES'
  # the CSS class of a dialog's button row and the brand text
  'web/*  .bt'
  'web/*  class="bt"'
  # the old name of SHAPELOGIC_USER_DATA, still read (and said so)
  'web/src/main/security.ts  BT_USER_DATA'
  'web/tests/unit/security.test.ts  BT_USER_DATA'
  'web/README.md  BT_USER_DATA'
  'site/src/content/docs/docs/code-base/commands.md  BT_USER_DATA'
  # gone from the code; the cleanup plan records them as they were
  'docs/CLEANUP-PLAN.md  BT_OLD_REPO'
  'docs/CLEANUP-PLAN.md  BT_TEST_SHARDS'
  'docs/CLEANUP-PLAN.md  bt_busy'
  'docs/CLEANUP-PLAN.md  bt_test_slide_session_'
  'docs/CLEANUP-PLAN.md  bt:log'
  'docs/CLEANUP-PLAN.md  bt:rescue'
  'docs/CLEANUP-PLAN.md  bt:ready'
)

allowed() {
  local path=$1 name=$2 entry glob
  while [[ $name == _* ]]; do name=${name#_}; done
  for entry in "${allow[@]}"; do
    glob=${entry%%  *}
    entry=${entry#*  }
    # shellcheck disable=SC2053
    if [[ $name == "$entry" && $path == $glob ]]; then return 0; fi
  done
  return 1
}

status=0
hits=$(git grep -P -I -n -o -e "$pattern" -- . "${skip[@]}") || status=$?
if [ "$status" -gt 1 ]; then
  echo "check-names: git grep failed (it needs PCRE: git grep -P)" >&2
  exit 2
fi
found=0
while IFS= read -r hit; do
  [ -n "$hit" ] || continue
  path=${hit%%:*}
  rest=${hit#*:}
  line=${rest%%:*}
  name=${rest#*:}
  if ! allowed "$path" "$name"; then
    echo "$path:$line: $name"
    found=$((found + 1))
  fi
done <<< "$hits"

if [ "$found" -gt 0 ]; then
  echo "check-names: $found old bt name(s) above; the new names are in docs/CLEANUP-BT-NAMES.md" >&2
  exit 1
fi
echo "check-names: no old bt name left"
